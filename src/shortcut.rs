//! Native `.app` shortcuts for installed titles.
//!
//! CrossOver has `cxmenu`, which publishes a bottle's Start Menu entries into
//! the Mac's Applications folder. This is the same idea reached differently:
//! one generated `.app` per title, so a Windows game launches from the Dock,
//! Spotlight or the Desktop exactly like a native application.
//!
//! The bundle is a tiny shell script rather than a compiled stub on purpose —
//! it is readable, editable, and carries the renderer tuning as plain `export`
//! lines, so a person can see and change what their game launches with.
//!
//! One rule earned the hard way: the script must call `exe-metal launch`,
//! never `exe-metal quit`-less kills. Many Windows games write their settings
//! only on a clean shutdown, so the generated bundle exposes graceful quit too.

use anyhow::{anyhow, Context, Result};
use std::path::{Path, PathBuf};

use crate::library::{Backend, Title};

/// Where generated bundles live. `~/Applications` keeps them out of the
/// system folder and needs no privilege escalation.
pub fn apps_dir() -> Result<PathBuf> {
    let home = std::env::var("HOME").map_err(|_| anyhow!("HOME is not set"))?;
    Ok(PathBuf::from(home).join("Applications"))
}

pub fn desktop_dir() -> Result<PathBuf> {
    let home = std::env::var("HOME").map_err(|_| anyhow!("HOME is not set"))?;
    Ok(PathBuf::from(home).join("Desktop"))
}

/// Strip characters that make a bundle name awkward on disk.
fn safe_name(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| if c == '/' || c == ':' { '-' } else { c })
        .collect();
    let t = cleaned.trim();
    if t.is_empty() {
        "Windows App".to_string()
    } else {
        t.to_string()
    }
}

fn bundle_id(title: &Title) -> String {
    let slug: String = title
        .id
        .chars()
        .map(|c| if c.is_alphanumeric() { c } else { '-' })
        .collect();
    format!("dev.navilan.exe-metal.{slug}")
}

/// The binary a generated bundle should call.
///
/// Not necessarily the running one. A build under `target/` disappears with the
/// next `cargo clean`, and every bundle pointing at it then fails without a
/// word — the Overwatch shortcut did exactly that. The installed copy on PATH
/// is the one that stays put.
fn stable_binary() -> PathBuf {
    let running = std::env::current_exe().unwrap_or_else(|_| PathBuf::from("exe-metal"));
    if running.components().any(|c| c.as_os_str() == "target") {
        if let Some(installed) = installed_binary() {
            return installed;
        }
    }
    running
}

/// Where `install.sh` puts the binary.
fn installed_binary() -> Option<PathBuf> {
    let dir = match std::env::var_os("EXE_METAL_PREFIX") {
        Some(p) => PathBuf::from(p),
        None => PathBuf::from(std::env::var_os("HOME")?).join(".local/bin"),
    };
    let p = dir.join("exe-metal");
    p.is_file().then_some(p)
}

/// Build (or rebuild) a `.app` for a title. Returns the bundle path.
pub fn create(title: &Title, also_desktop: bool) -> Result<PathBuf> {
    let name = safe_name(&title.name);
    let app = apps_dir()?.join(format!("{name}.app"));
    let macos = app.join("Contents/MacOS");
    std::fs::create_dir_all(&macos).with_context(|| format!("creating {}", macos.display()))?;

    let plist = format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>{name}</string>
  <key>CFBundleDisplayName</key><string>{name}</string>
  <key>CFBundleIdentifier</key><string>{id}</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
</dict>
</plist>
"#,
        name = name,
        id = bundle_id(title)
    );
    std::fs::write(app.join("Contents/Info.plist"), plist)?;

    let exe = stable_binary().to_string_lossy().to_string();

    let backend_note = match title.backend {
        Backend::CrossOver => "# Runs in a CrossOver bottle.",
        Backend::ExeMetal => "# Runs in an exe-metal bottle.",
    };

    let script = format!(
        r#"#!/bin/zsh
# Generated by exe-metal. Safe to edit; regenerate with:
#   exe-metal shortcut {id}
{backend_note}
exec >"/tmp/exe-metal-{id}.log" 2>&1

# Say so when the binary is gone, rather than doing nothing at all.
if [[ ! -x "{exe}" ]]; then
  /usr/bin/osascript -e 'display alert "exe-metal is missing" message "This shortcut runs {exe}, which no longer exists. Reinstall with ./install.sh, then run: exe-metal shortcut {id}"'
  exit 1
fi

# Renderer tuning. MetalFX upscaling on; DXR off, because D3DMetal turns it on
# by default for M3 and later and most titles never ask for ray tracing.
export D3DM_ENABLE_METALFX=${{EXE_METAL_METALFX:-1}}
export D3DM_SUPPORT_DXR=${{EXE_METAL_DXR:-0}}
# Metal's FPS overlay, for when something feels slow. EXE_METAL_HUD=1 to show it.
export MTL_HUD_ENABLED=${{EXE_METAL_HUD:-0}}

exec "{exe}" launch "{id}"
"#,
        id = title.id,
        exe = exe,
        backend_note = backend_note
    );
    let launcher = macos.join("launch");
    std::fs::write(&launcher, script)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&launcher, std::fs::Permissions::from_mode(0o755))?;
    }

    // Register so Spotlight and the Dock pick it up immediately rather than
    // whenever LaunchServices next rescans.
    let _ = std::process::Command::new(
        "/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister",
    )
    .arg("-f")
    .arg(&app)
    .stdout(std::process::Stdio::null())
    .stderr(std::process::Stdio::null())
    .status();

    if also_desktop {
        let link = desktop_dir()?.join(format!("{name}.app"));
        let _ = std::fs::remove_file(&link);
        // A symlink rather than a copy: one bundle, one place to update.
        let _ = std::os::unix::fs::symlink(&app, &link);
    }

    Ok(app)
}

/// Remove a title's generated bundle and any Desktop link.
pub fn remove(title: &Title) -> Result<bool> {
    let name = safe_name(&title.name);
    let app = apps_dir()?.join(format!("{name}.app"));
    let link = desktop_dir()?.join(format!("{name}.app"));
    let _ = std::fs::remove_file(&link);
    if app.exists() {
        std::fs::remove_dir_all(&app)?;
        return Ok(true);
    }
    Ok(false)
}

/// Guard against generating a bundle for something that cannot run.
pub fn check_launchable(title: &Title) -> Result<()> {
    if !Path::new(&title.exe).is_file() {
        anyhow::bail!(
            "'{}' points at a file that no longer exists:\n  {}",
            title.name,
            title.exe.display()
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_with_slashes_do_not_escape_the_folder() {
        assert_eq!(safe_name("Command/Conquer"), "Command-Conquer");
        assert_eq!(safe_name("a:b"), "a-b");
        assert_eq!(safe_name("   "), "Windows App");
        assert_eq!(safe_name(""), "Windows App");
    }

    #[test]
    fn bundle_ids_are_reverse_dns_and_punctuation_free() {
        let t = Title {
            id: "poppy-playtime".into(),
            name: "Poppy Playtime".into(),
            bottle: "b".into(),
            exe: "/x/y.exe".into(),
            kind: crate::library::TitleKind::App,
            added: 0,
            last_played: None,
            play_count: 0,
            installer: None,
            renamed: false,
            backend: Backend::ExeMetal,
        };
        let id = bundle_id(&t);
        assert!(id.starts_with("dev.navilan.exe-metal."));
        assert!(!id.contains(' '));
    }
}
